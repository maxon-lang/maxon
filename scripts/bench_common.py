def mark_ref_used(entry):
    pathlib.Path(entry, REF_USED_MARKER).touch()


# Retries only a failed delete: `shutil.rmtree` cannot resume after a failed `os.open`, so any other
# failure is raised.
def make_writable_and_retry(function, path, failure):
    error = failure[1] if isinstance(failure, tuple) else failure
    if function not in (os.unlink, os.remove, os.rmdir):
        raise error
    try:
        os.chmod(os.path.dirname(path), stat.S_IRWXU)
        os.chmod(path, stat.S_IRWXU)
        function(path)
    except OSError:
        raise error from None


def remove_tree(path):
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=make_writable_and_retry)
    else:
        shutil.rmtree(path, onerror=make_writable_and_retry)


def remove_worktree(tree):
    if run(["git", "-C", REPO, "worktree", "remove", "--force", tree]).returncode != 0:
        if os.path.exists(tree):
            remove_tree(tree)
        git(REPO, "worktree", "prune")


def discard_ref_entry(entry):
    tree = os.path.join(entry, REF_BUILD_TREE_NAME)
    if os.path.exists(tree):
        remove_worktree(tree)
    remove_tree(entry)


# An entry is laid out as the compiler's walk-up finds a checkout: `stdlib/`, with `runtime/` and
# `scriptlib/` beside it (`runtimeDirBeside`, `scriptlibDirBeside`). `vendor/` is absent because the
# wasm lane resolves it from the working directory. The compiler is copied last, so a compiler in an
# entry means the install is complete: `build_compiler_from_ref` and `prune_ref_cache` test for it.
def install_ref_compiler(tree, entry):
    for name in LIBRARY_DIR_NAMES:
        source = os.path.join(tree, name)
        if os.path.isdir(source):
            shutil.copytree(source, os.path.join(entry, name))
        elif name == STDLIB_DIR_NAME:
            raise BuildFailure(f"{tree} has no {STDLIB_DIR_NAME}/, which its compiler finds by walking up from itself")
    mark_ref_used(entry)
    compiler = installed_compiler_of(entry)
    os.makedirs(os.path.dirname(compiler), exist_ok=True)
    staging = compiler + PARTIAL_SUFFIX
    shutil.copy2(os.path.join(tree, *COMPILER_SEGMENTS), staging)
    os.replace(staging, compiler)


def build_ref_entry(sha, entry):
    shell = posix_shell()
    if os.path.exists(entry):
        discard_ref_entry(entry)
    tree = os.path.join(entry, REF_BUILD_TREE_NAME)
    os.makedirs(entry)
    git(REPO, "worktree", "add", "--detach", tree, sha)
    try:
        build_in_worktree(sha, shell, tree, entry)
    except BaseException as failure:
        # Removed here rather than after the `try`, so a cleanup failure is reported together with
        # the build failure instead of replacing it.
        try:
            remove_worktree(tree)
        except Exception as cleanup:
            raise BuildFailure(f"{str(failure) or type(failure).__name__}\n\nand removing the worktree {tree} then failed too:\n{cleanup}") from failure
        raise
    remove_worktree(tree)


def build_in_worktree(sha, shell, tree, entry):
    print(f"building a compiler from {sha} in {tree} ...", flush=True)
    place_ref_seed(shell, tree)
    run_tree_script(shell, tree, SEED_BUILD_SCRIPT)
    built = os.path.join(tree, *COMPILER_SEGMENTS)
    if not os.path.exists(built):
        raise BuildFailure(f"{SEED_BUILD_SCRIPT} in {tree} exited 0 and left no compiler at {built}")
    install_ref_compiler(tree, entry)


def build_compiler_from_ref(sha, out_dir):
    entry = ref_entry_of(sha, out_dir)
    compiler = installed_compiler_of(entry)
    if os.path.exists(compiler):
        mark_ref_used(entry)
    else:
        build_ref_entry(sha, entry)
    return compiler


def ref_entries(out_dir):
    return {name[len(REF_ENTRY_PREFIX):]: os.path.join(out_dir, name) for name in sorted(os.listdir(out_dir))
            if REF_ENTRY_PATTERN.match(name) and os.path.isdir(os.path.join(out_dir, name))}


def remove_ref_arm_directories(out_dir, shas):
    labels = {ref_label(sha) for sha in shas}
    for root, directories, _ in os.walk(out_dir):
        for name in directories:
            if name in labels:
                remove_tree(os.path.join(root, name))
        directories[:] = [name for name in directories
                          if name not in labels and not (root == out_dir and REF_ENTRY_PATTERN.match(name))]


def prune_ref_cache(out_dir, keep_refs, protected_shas):
    entries = ref_entries(out_dir)
    protected = set(protected_shas)
    unprotected = [sha for sha in entries if sha not in protected]
    unusable = [sha for sha in unprotected if not os.path.exists(installed_compiler_of(entries[sha]))]
    usable = [sha for sha in unprotected if sha not in unusable]
    most_recent_first = sorted(usable, key=lambda sha: (os.path.getmtime(os.path.join(entries[sha], REF_USED_MARKER)), sha),
                               reverse=True)
    evicted = unusable + most_recent_first[max(0, keep_refs - len(protected)):]
    if evicted:
        for sha in evicted:
            discard_ref_entry(entries[sha])
        remove_ref_arm_directories(out_dir, evicted)
        print(f"ref compilers in {out_dir}: deleted {len(evicted)} ({', '.join(evicted)}), kept {len(entries) - len(evicted)}", flush=True)


def check_output_root(out_dir):
    if os.path.lexists(os.path.join(out_dir, GIT_ENTRY_NAME)):
        raise UsageFailure(f"{out_dir} holds a {GIT_ENTRY_NAME}, so it is a checkout and not a bench output directory; "
                           "the harness would mark all of it ignored and delete from it")
    resolved = os.path.normcase(os.path.realpath(out_dir))
    repo = os.path.normcase(os.path.realpath(REPO))
    try:
        encloses_repo = os.path.commonpath([resolved, repo]) == resolved
    except ValueError:
        encloses_repo = False
    if encloses_repo:
        raise UsageFailure(f"{out_dir} is this repository or one of its parents; --out-dir names a directory of generated output")


def lock_exclusively(fd):
    if IS_WINDOWS:
        import msvcrt
        os.lseek(fd, LOCK_REGION_OFFSET, os.SEEK_SET)
        try:
            msvcrt.locking(fd, msvcrt.LK_NBLCK, LOCK_REGION_BYTES)
        finally:
            os.lseek(fd, 0, os.SEEK_SET)
    else:
        import fcntl
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)


def lock_holder(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read().strip() or "a run that has not yet recorded itself"
    except OSError:
        return "a run that could not be read"


def hold_output_root(out_dir):
    key = os.path.normcase(os.path.abspath(out_dir))
    if key in HELD_LOCKS:
        raise UsageFailure(f"{out_dir} is already in use by this process")
    path = os.path.join(out_dir, LOCK_FILE_NAME)
    fd = os.open(path, os.O_RDWR | os.O_CREAT | getattr(os, "O_BINARY", 0))
    try:
        lock_exclusively(fd)
    except (BlockingIOError, PermissionError):
        os.close(fd)
        raise UsageFailure(f"{out_dir} is in use by {lock_holder(path)}; wait for it to finish, or give this run its own --out-dir") from None
    except BaseException:
        os.close(fd)
        raise
    os.ftruncate(fd, 0)
    os.write(fd, f"pid {os.getpid()}: {' '.join(sys.argv)}".encode("utf-8"))
    HELD_LOCKS[key] = fd


def release_output_root(out_dir):
    fd = HELD_LOCKS.pop(os.path.normcase(os.path.abspath(out_dir)), None)
    if fd is not None:
        os.close(fd)


def open_output_root(out_dir, keep_refs, plan):
    check_output_root(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    marker = os.path.join(out_dir, IGNORE_MARKER_NAME)
    if not os.path.exists(marker):
        with open(marker, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(IGNORE_MARKER_TEXT)
    hold_output_root(out_dir)
    shas = [arm["sha"] for arm in plan if is_ref_arm(arm)]
    for sha in shas:
        entry = ref_entry_of(sha, out_dir)
        if os.path.exists(installed_compiler_of(entry)):
            mark_ref_used(entry)
    prune_ref_cache(out_dir, keep_refs, shas)


def arm_identity(planned, compiler):
    identity = {"compiler": os.path.abspath(compiler),
                "bytes": os.path.getsize(compiler),
                "mtime": datetime.datetime.fromtimestamp(os.path.getmtime(compiler)).isoformat(timespec="seconds")}
    if is_ref_arm(planned):
        # Built in a worktree of exactly this sha, so it is clean. `checkout_root_of` is not asked:
        # the entry may sit inside another checkout (the default out-dirs do), whose HEAD it would
        # report.
        identity["head"] = planned["sha"]
        identity["dirty"] = False
        return identity
    root = checkout_root_of(compiler)
    if root:
        head, dirty = tree_identity(root)
        identity["checkout"] = root
        identity["head"] = head
        identity["dirty"] = dirty
    return identity


def profile_arm(arm, program_arguments, hz, report_name):
    """`maxon profile run` with the arm's own compiler; the report is saved beside the binary."""
    cmd = [arm["compiler"], "profile", "run", f"--rate={hz}", arm["exe"]] + list(program_arguments)
    where = f"profile of {arm['label']} with arguments {list(program_arguments)}"
    try:
        r = run(cmd, cwd=arm["dir"], timeout=RUN_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        raise VerificationFailure(f"{where} timed out after {RUN_TIMEOUT_S} s") from None
    if r.returncode != 0:
        raise VerificationFailure(f"{where} failed (exit {r.returncode}):\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    path = os.path.join(arm["dir"], report_name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(r.stdout)
        fh.write(r.stderr)
    return path, r.stdout


def hot_functions_section(report):
    lines = report.splitlines()
    out = []
    keep = False
    for line in lines:
        if line.startswith("=== hot functions"):
            keep = True
        elif line.startswith("=== ") and keep:
            break
        if keep:
            out.append(line)
    return "\n".join(out)


def timed_run(exe, n, cwd):
    start = time.perf_counter()
    try:
        result = run([exe, str(n)], cwd=cwd, timeout=RUN_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        raise VerificationFailure(f"{exe} {n} timed out after {RUN_TIMEOUT_S} s") from None
    return (time.perf_counter() - start) * MILLIS, result


def fmt_ms(value):
    return f"{value:,.0f}"


def tidy_output_roots(args):
    for out_dir in args.out_dirs:
        if not os.path.isdir(out_dir):
            raise UsageFailure(f"{out_dir} is not a directory")
    for out_dir in args.out_dirs:
        open_output_root(os.path.abspath(out_dir), args.keep_refs, [])
    return EXIT_OK


def main():
    ap = argparse.ArgumentParser(description="Mark bench output directories as generated and delete the ref compilers "
                                             "they no longer need: unusable entries, then the least recently used "
                                             "beyond --keep-refs.")
    ap.add_argument("out_dirs", nargs="+", help="a bench harness's --out-dir, e.g. bench/aes/out")
    add_keep_refs_argument(ap)
    args = ap.parse_args()
    try:
        check_keep_refs(args.keep_refs)
        return tidy_output_roots(args)
    except (UsageFailure, BuildFailure) as e:
        return report_failure(e)


if __name__ == "__main__":
    sys.exit(main())
