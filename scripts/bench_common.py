def plan_arms(args, allow_no_arms=False, reserved_labels=()):
    """Every arm in run order with its final label - ref arms FIRST, so an A/B's control is the first one.

    A ref is resolved to its sha HERE and built from that sha later, so every label is known before a
    compiler is built and a duplicate costs nothing; it also keeps the label and the binary in
    agreement if the ref moves mid-run.
    """
    plan = []
    for ref in args.ref:
        sha = git(REPO, "rev-parse", "--short", ref)
        plan.append({"label": ref_label(sha), "sha": sha, "compiler": None})
    for i, compiler in enumerate(args.compiler):
        label = args.label[i] if args.label else f"compiler{i + 1}"
        plan.append({"label": label, "sha": None, "compiler": os.path.abspath(compiler)})
    if not args.no_slot:
        plan.append({"label": SLOT_LABEL, "sha": None, "compiler": SLOT_COMPILER})
    if not plan and not allow_no_arms:
        raise UsageFailure("nothing to run")

    reserved = {label.casefold(): label for label in reserved_labels}
    seen = {}
    for arm in plan:
        label = arm["label"]
        key = label.casefold()
        if key in reserved:
            raise UsageFailure(f"an arm may not be labelled {label!r}; {reserved[key]!r} names this bench's own reference arm")
        if key in seen:
            raise UsageFailure(f"two arms are labelled {seen[key]!r} and {label!r}; a label names an arm's output directory "
                               "(case-insensitively on Windows) and its timing list, so they would share both and report "
                               "a ratio of 1.00 as verified")
        seen[key] = label
    return plan


def is_ref_arm(planned):
    return planned["sha"] is not None


def arm_compiler(planned, out_dir):
    if is_ref_arm(planned):
        return build_compiler_from_ref(planned["sha"], out_dir)
    if not os.path.exists(planned["compiler"]):
        raise BuildFailure(f"arm {planned['label']} has no compiler at {planned['compiler']}; build it or drop the arm")
    return planned["compiler"]


def repo_relative(path):
    try:
        relative = os.path.relpath(os.path.abspath(path), REPO)
    except ValueError:
        return None
    return None if relative == os.pardir or relative.startswith(os.pardir + os.sep) else relative


def arm_source(planned, out_dir, source):
    relative = repo_relative(source)
    if relative is None:
        return os.path.abspath(source)
    if is_ref_arm(planned):
        return write_ref_source(planned, out_dir, relative)
    path = os.path.join(REPO, relative)
    if not os.path.isfile(path):
        raise BuildFailure(f"arm {planned['label']} has no {relative.replace(os.sep, '/')} in its checkout {REPO}")
    return path


def ref_holds(planned, relative):
    """Whether the ref arm's commit has the file at this repository-relative path."""
    posix = relative.replace(os.sep, "/")
    return subprocess.run(["git", "-C", REPO, "cat-file", "-e", f"{planned['sha']}:{posix}"], capture_output=True).returncode == 0


def arm_companions(planned, out_dir, companions):
    """The companion sources this arm compiles beside its program. A ref arm compiles what its commit holds, so a
    companion the commit lacks (a program that predates the shared source it is built with now) is left out."""
    held = []
    for companion in companions:
        relative = repo_relative(companion)
        if is_ref_arm(planned) and relative is not None and not ref_holds(planned, relative):
            continue
        held.append(arm_source(planned, out_dir, companion))
    return held


def write_ref_source(planned, out_dir, relative):
    posix = relative.replace(os.sep, "/")
    blob = subprocess.run(["git", "-C", REPO, "cat-file", "blob", f"{planned['sha']}:{posix}"], capture_output=True)
    if blob.returncode != 0:
        raise BuildFailure(f"arm {planned['label']} has no {posix} in commit {planned['sha']}; "
                           f"a ref arm compiles its own commit's program, never this tree's\n{blob.stderr.decode(errors='replace')}")
    path = os.path.join(ref_entry_of(planned["sha"], out_dir), REF_SOURCES_DIR_NAME, relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(blob.stdout)
    return path


