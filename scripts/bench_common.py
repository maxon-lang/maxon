def go_query(go, env, *arguments):
    answer = run([go] + list(arguments), env=env)
    if answer.returncode != 0:
        raise BuildFailure(f"{go} {' '.join(arguments)} failed:\n{answer.stderr}")
    return answer.stdout.strip()


