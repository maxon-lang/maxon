#!/bin/sh
#
# Usage:
#   scripts/targets/generate.sh           write maxon-bin/Compiler/TargetsGenerated.maxon
#   scripts/targets/generate.sh --check   write nothing; exit 1 when the committed file differs
#
# Exit codes: 0 clean, 1 drift (--check), 2 malformed table or usage.

set -eu

ExitClean=0
ExitDrift=1
ExitFailed=2

GeneratedPath="maxon-bin/Compiler/TargetsGenerated.maxon"
GeneratorPath="scripts/targets/generate.sh"

repo_root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$repo_root"

check=0

case "$#:${1:-}" in
	0:) ;;
	1:--check) check=1 ;;
	*)
		echo "usage: $GeneratorPath [--check]" >&2
		exit "$ExitFailed"
		;;
esac

unset MAXON_TARGETS_TABLE
# shellcheck source=scripts/lib/host-binaries.sh
. scripts/lib/host-binaries.sh || exit "$ExitFailed"

rows="$(maxon_table_select target,debugger)" || exit "$ExitFailed"

scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT INT TERM
produced="$scratch/TargetsGenerated.maxon"

status=0
printf '%s\n' "$rows" | awk -F "$TableSeparator" -v table="$MAXON_TARGETS_TABLE" -v generator="$GeneratorPath" '
BEGIN {
	targetCount = 0
	debuggerCount = 0
}

function fail(message) {
	print generator ": " table ": " message > "/dev/stderr"
	failed = 1
	exit 2
}

function targetCall(target,    dash, cpu, os) {
	dash = index(target, "-")
	if (dash == 0) {
		fail("target \"" target "\" is not <cpu>-<os>")
	}
	cpu = substr(target, 1, dash - 1)
	os = substr(target, dash + 1)
	if (cpu !~ /^[a-z][a-z0-9]*$/ || os !~ /^[a-z][a-z0-9]*$/) {
		fail("target \"" target "\" is not <cpu>-<os> in lower-case letters and digits")
	}
	return "Target.create(CpuArch." cpu ", os: Os." os ")"
}

function joinedList(calls, count,    i, out) {
	out = ""
	for (i = 1; i <= count; i++) {
		out = out (i > 1 ? ", " : "") calls[i]
	}
	return "[" out "]"
}

$0 == "" {
	next
}

{
	target = $1
	if (target in seen) {
		fail("target \"" target "\" is listed twice")
	}
	seen[target] = 1
	call = targetCall(target)
	targetCount++
	targetCalls[targetCount] = call
	debugger = $2
	if (debugger == "yes") {
		debuggerCount++
		debuggerCalls[debuggerCount] = call
	} else if (debugger != "no") {
		fail("the debugger of \"" target "\" is \"" debugger "\", not yes or no")
	}
}

END {
	if (failed) {
		exit 2
	}
	if (targetCount == 0) {
		fail("the table has a header and no target rows")
	}
	if (debuggerCount == 0) {
		fail("no target has a debugger")
	}
	print "// @generated by " generator " from " table "; edit the table and run the script, never this file"
	print ""
	print "// The one list. `SpecVerdictSelfTest` sweeps it, and must cover every target or it is scoped to"
	print "// whichever its author thought of."
	print "export function supportedTargets() returns TargetArray"
	print "\treturn " joinedList(targetCalls, targetCount)
	print "end '"'"'supportedTargets'"'"'"
	print ""
	print "// Which debug interface serves each is `debugInterfaceOf` in `BackendChoice.maxon`, which panics on"
	print "// a target listed here that it has no arm for."
	print "export function debuggerTargets() returns TargetArray"
	print "\treturn " joinedList(debuggerCalls, debuggerCount)
	print "end '"'"'debuggerTargets'"'"'"
}
' > "$produced" || status=$?

if [ "$status" -ne 0 ]; then
	exit "$ExitFailed"
fi

if [ "$check" -eq 1 ]; then
	if [ ! -f "$GeneratedPath" ] || ! cmp -s "$produced" "$GeneratedPath"; then
		echo "$GeneratorPath: $GeneratedPath differs from $MAXON_TARGETS_TABLE; run $GeneratorPath to regenerate it" >&2
		exit "$ExitDrift"
	fi
	exit "$ExitClean"
fi

cp "$produced" "$GeneratedPath"
