#!/usr/bin/env bash
# THE MANAGED-PRIMITIVE SCAN LADDER — what `inlineManagedPrimitives` costs per OP in a program that holds
# no site at all.
#
# `ScaleCorpus` cannot isolate it: every rung holds expandable sites, so the pass's per-op walk is never
# read apart from the expansions it performs.
#
# Usage: genmanagedsites.sh <n> nosites <outdir>
#   <n>    = THE DOUBLING KNOB.
#   mode   = nosites — <n> straight-line statements and NOT ONE managed primitive: what the pass costs for
#                      merely WALKING a program it expands nothing in.
#   outdir = the project directory to write (CREATED AND OVERWRITTEN; its `*.maxon` are pruned first).
#
#   e.g. genmanagedsites.sh 512 nosites temp/mp-none-512/
#
# Read it with `--metrics`, whose `phase` rows carry the exact allocation counts:
#
#     maxon build temp/mp-none-512/ --output=temp/mp.exe --metrics=temp/mp.tsv
#     grep inlineManagedPrimitives temp/mp.tsv          # nanos, allocs, frees, bytes, cputicks
#
# ⚠ **READ THE ALLOCATION AND BYTE COLUMNS — they are exact and bit-reproducible, so a ratio off them
# is a datapoint on the first run.** And because the ladder DOUBLES, the RATIO between consecutive <n>
# IS the growth: x2 linear, x4 quadratic. Nothing to fit.
#
# ⭐⭐ **`nosites` GUARDS THE PASS'S PER-OP PATH AGAINST A PAYLOAD-BEARING UNION.** The pass visits every
# op of every reachable function, and such a union heap-boxes EVERY case including the payload-free ones,
# so one on that path costs allocations per Std op in the program. `expandAt` answers with a `BlockRef` (an
# integer) for that reason. A flat row is the answer; a row that grows with <n> means a union got back onto
# the per-op path.

set -euo pipefail

if [ $# -ne 3 ]; then
	echo "usage: genmanagedsites.sh <n> nosites <outdir>" >&2
	exit 2
fi

N="$1"
MODE="$2"
OUT="$3"

case "$MODE" in
	nosites) ;;
	*) echo "genmanagedsites.sh: mode must be nosites, got '$MODE'" >&2; exit 2 ;;
esac

mkdir -p "$OUT"
rm -f "$OUT"/*.maxon

# ONE FILE PER RUNG, prelude and driver included. A ladder that moves ONE axis has no business also
# moving the file count, and a multi-file spelling would need an `export` on every generated function
# (E3008) plus whatever `checkUnusedExports` then makes of them — two mechanisms this measurement has
# nothing to say about, standing between the knob and the phase it is aimed at.
#
# `mpOpaque` is what makes each statement real: a value the parser folds is settled at compile time and
# the statement can vanish before this pass ever walks it.

{
	echo "// Generated by genmanagedsites.sh — $MODE ladder, n=$N."
	echo "typealias LadderInt = int(i64.min to i64.max)"
	echo "function mpOpaque(a LadderInt) returns LadderInt"
	echo "	if a > 100 'big'"
	echo "		return a - 100"
	echo "	end 'big'"
	echo "	return a + 1"
	echo "end 'mpOpaque'"

	echo "function mpNone(a LadderInt) returns LadderInt"
	echo "	var acc = 0"
	for ((i = 0; i < N; i++)); do
		echo "	acc = acc + mpOpaque(a + $i)"
	done
	echo "	return acc"
	echo "end 'mpNone'"

	echo "function main() returns ExitCode"
	echo "	print(\"{mpNone(7)}\")"
	echo "	return 0"
	echo "end 'main'"
} > "$OUT/a_sites.maxon"

echo "genmanagedsites.sh: wrote $MODE ladder with n=$N to $OUT"
